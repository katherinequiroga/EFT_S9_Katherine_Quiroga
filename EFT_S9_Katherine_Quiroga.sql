-- CREACION DE TABLAS EN ORDEN DE DEPENDENCIA
CREATE TABLE REGION (
  id_region NUMBER NOT NULL,
  nombre_region VARCHAR2(100) NOT NULL
);
ALTER TABLE REGION ADD CONSTRAINT REGION_PK PRIMARY KEY (id_region);

CREATE TABLE NACIONALIDAD (
  id_nacionalidad NUMBER GENERATED AS IDENTITY (START WITH 210 INCREMENT BY 2) NOT NULL,
  nombre_nacionalidad VARCHAR2(100) NOT NULL
);
ALTER TABLE NACIONALIDAD ADD CONSTRAINT NACIONALIDAD_PK PRIMARY KEY (id_nacionalidad);

CREATE TABLE ASOCIACION (
  id_asociacion NUMBER NOT NULL,
  nombre_asociacion VARCHAR2(100) NOT NULL,
  fecha_creacion DATE NOT NULL,
  tipo_asociacion CHAR(1) NOT NULL,
  CONSTRAINT chk_fecha_asoc CHECK (fecha_creacion >= TO_DATE('31/12/1980','DD/MM/YYYY'))
);
ALTER TABLE ASOCIACION ADD CONSTRAINT ASOCIACION_PK PRIMARY KEY (id_asociacion);

CREATE TABLE COMUNA (
  id_comuna NUMBER NOT NULL,
  nombre_comuna VARCHAR2(100) NOT NULL,
  REGION_id_region NUMBER NOT NULL
);
ALTER TABLE COMUNA ADD CONSTRAINT COMUNA_PK PRIMARY KEY (id_comuna);

CREATE TABLE CLUB_FUTBOL (
  id_club NUMBER NOT NULL,
  nombre_club VARCHAR2(100) NOT NULL,
  patrimonio NUMBER NOT NULL,
  direccion VARCHAR2(200),
  COMUNA_id_comuna NUMBER,
  ASOCIACION_id_asociacion NUMBER,
  CONSTRAINT CLUB_FUTBOL_NOMBRE_UK UNIQUE (nombre_club)
);
ALTER TABLE CLUB_FUTBOL ADD CONSTRAINT CLUB_FUTBOL_PK PRIMARY KEY (id_club);

CREATE TABLE TRABAJADOR (
  rut_trabajador NUMBER NOT NULL,
  dv_trabajador CHAR(1) NOT NULL,
  nombres VARCHAR2(100) NOT NULL,
  apellidos VARCHAR2(100) NOT NULL,
  sueldo_base NUMBER NOT NULL,
  fecha_nacimiento DATE NOT NULL,
  genero CHAR(1),
  estado_civil VARCHAR2(20),
  telefono_movil VARCHAR2(20),
  direccion VARCHAR2(200),
  CLUB_FUTBOL_id_club NUMBER,
  NACIONALIDAD_id_nacionalidad NUMBER,
  COMUNA_id_comuna NUMBER
);
ALTER TABLE TRABAJADOR ADD CONSTRAINT TRABAJADOR_PK PRIMARY KEY (rut_trabajador);

CREATE TABLE JUGADOR (
  rut_trabajador NUMBER NOT NULL,
  puesto VARCHAR2(50),
  total_premios NUMBER,
  ESCUELA_FUTBOL_id_escuela NUMBER
);
ALTER TABLE JUGADOR ADD CONSTRAINT JUGADOR_PK PRIMARY KEY (rut_trabajador);

CREATE TABLE PERSONAL_PLANTA (
  rut_trabajador NUMBER NOT NULL,
  horas_trabajadas NUMBER,
  valor_hora_extra NUMBER
);
ALTER TABLE PERSONAL_PLANTA ADD CONSTRAINT PERSONAL_PLANTA_PK PRIMARY KEY (rut_trabajador);

CREATE TABLE IDIOMA (
  id_idioma NUMBER NOT NULL,
  nombre_idioma VARCHAR2(50) NOT NULL
);
ALTER TABLE IDIOMA ADD CONSTRAINT IDIOMA_PK PRIMARY KEY (id_idioma);

CREATE TABLE ESCUELA_FUTBOL (
  id_escuela NUMBER NOT NULL,
  nombre_escuela VARCHAR2(100) NOT NULL,
  capacidad NUMBER NOT NULL,
  fecha_fundacion DATE NOT NULL,
  CLUB_FUTBOL_id_club NUMBER
);
ALTER TABLE ESCUELA_FUTBOL ADD CONSTRAINT ESCUELA_FUTBOL_PK PRIMARY KEY (id_escuela);

CREATE TABLE HISTORICO_CLUB (
  id_historico NUMBER NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE,
  TRABAJADOR_rut_trabajador NUMBER,
  CLUB_FUTBOL_id_club NUMBER
);
ALTER TABLE HISTORICO_CLUB ADD CONSTRAINT HISTORICO_CLUB_PK PRIMARY KEY (id_historico);

CREATE TABLE JUGADOR_IDIOMA (
  rut_jugador_fk NUMBER NOT NULL,
  id_idioma_fk NUMBER NOT NULL,
  nivel_dominio NUMBER NOT NULL,
  JUGADOR_rut_trabajador NUMBER,
  IDIOMA_id_idioma NUMBER
);
ALTER TABLE JUGADOR_IDIOMA ADD CONSTRAINT JUGADOR_IDIOMA_PK PRIMARY KEY (rut_jugador_fk, id_idioma_fk);

